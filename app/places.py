_COUNTRY_PATTERN = re.compile(
    r"\b(?:" + "|".join(re.escape(name) for name in sorted(_COUNTRIES, key=len, reverse=True)) + r")\b",
    re.I,
)


def mentions_international(text: str) -> bool:
    """True when the text names a place outside the United States."""
    if not text:
        return False
    if _INTERNATIONAL_WORDS.search(text):
        return True
    masked = _US_PLACES.sub(" ", text)
    return _COUNTRY_PATTERN.search(masked) is not None
